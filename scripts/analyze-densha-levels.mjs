// Labels every Kaiten Express level (owner request, 22 November 2026) so weak levels can be filtered
// and good ones ordered by complexity. Uses the proven optimal plan for each level (puzzle-contracts.ts)
// plus a full state search for traps. Writes prototypes/densha-domino/level-report.md and .csv.
// Usage: node scripts/analyze-densha-levels.mjs
import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = await build({
  stdin: { contents: "export {LEVELS} from './prototypes/densha-domino/src/game/levels';export {PUZZLE_CONTRACTS} from './prototypes/densha-domino/src/game/puzzle-contracts';export {applyTap,initialState,legalMoves,isCleared} from './prototypes/densha-domino/src/game/rules';", resolveDir: root, loader: 'ts' },
  bundle: true, platform: 'node', format: 'esm', write: false, logLevel: 'error',
});
const R = await import('data:text/javascript;base64,' + Buffer.from(out.outputFiles[0].text).toString('base64'));

/** Distance (moves) from every reachable state to the cleared board, by full search. */
function distances(level) {
  const key = (s) => String.fromCharCode(...s.map((p) => p + 2));
  const ids = new Map(), states = [], edges = [];
  const add = (s) => { const k = key(s); let id = ids.get(k); if (id === undefined) { id = states.length; ids.set(k, id); states.push(s); edges.push([]); } return id; };
  add(R.initialState(level));
  for (let i = 0; i < states.length; i++) {
    if (states.length > 400000) return null;
    if (R.isCleared(states[i])) continue;
    for (const m of R.legalMoves(level, states[i])) { const r = R.applyTap(level, states[i], m); edges[i].push({ to: add(r.state), move: m, exited: r.exited }); }
  }
  const goal = ids.get(key(level.trains.map(() => -1)));
  const preds = states.map(() => []);
  edges.forEach((l, f) => l.forEach((e) => preds[e.to].push(f)));
  const dist = new Int32Array(states.length).fill(-1);
  dist[goal] = 0;
  const q = [goal];
  for (let i = 0; i < q.length; i++) for (const p of preds[q[i]]) if (dist[p] < 0) { dist[p] = dist[q[i]] + 1; q.push(p); }
  return { ids, key, edges, dist, states: states.length };
}

const rows = [];
for (const [i, level] of R.LEVELS.entries()) {
  const c = R.PUZZLE_CONTRACTS.find((x) => x.name === level.name);
  const g = distances(level);
  let state = R.initialState(level);
  let singles = 0, setups = 0, reverses = 0, chains = 0, biggest = 0, payoffs = 0, traps = 0, trapCost = 0, prevSetup = false;
  const steps = [];
  for (const m of c.plan) {
    // Traps at this step: moves that send 2+ trains off now but are not on any shortest path.
    if (g) {
      const here = g.dist[g.ids.get(g.key(state))];
      for (const e of g.edges[g.ids.get(g.key(state))]) {
        const after = g.dist[e.to];
        if (e.exited >= 2 && (after < 0 || after > here - 1)) { traps++; trapCost = Math.max(trapCost, after < 0 ? 99 : after + 1 - here); }
      }
    }
    const t = level.trains[m.train];
    const r = R.applyTap(level, state, m);
    const bumps = r.events.filter((e) => e.type === 'hit').length;
    if (r.exited === 0) { setups++; if (m.dir !== t.headDir) reverses++; }
    else if (r.exited === 1 && bumps === 0) singles++;
    if (r.exited >= 2) chains++;
    if (r.exited >= 3 && prevSetup) payoffs++;
    prevSetup = r.exited === 0;
    biggest = Math.max(biggest, r.exited);
    steps.push(r.exited === 0 ? (m.dir !== t.headDir ? 'R' : 'S') : String(r.exited));
    state = r.state;
  }
  rows.push({
    level: i + 1, name: level.name, size: `${level.cols}x${level.rows}`, trains: level.trains.length, par: c.plan.length,
    singles, setups, reverses, chains, biggest, payoffs, traps, trapCost: trapCost >= 99 ? 'stuck' : trapCost, states: g?.states ?? '>400k',
    moves: steps.join(' '),
  });
}

const cols = ['level', 'name', 'size', 'trains', 'par', 'singles', 'setups', 'reverses', 'chains', 'biggest', 'payoffs', 'traps', 'trapCost', 'states', 'moves'];
fs.writeFileSync(path.join(root, 'prototypes/densha-domino/level-report.csv'), [cols.join(','), ...rows.map((r) => cols.map((k) => JSON.stringify(r[k])).join(','))].join('\n') + '\n');
const md = [
  '# Kaiten Express level report',
  '',
  'Generated by `node scripts/analyze-densha-levels.mjs` from the proven optimal plan of each level.',
  '',
  '- **singles**: moves that send one train off with no bump (boring).',
  '- **setups**: moves that send nothing off (repositioning); **reverses**: setups that drive a train away from its face.',
  '- **chains**: moves sending 2+ trains off; **biggest**: most trains sent off by one move.',
  '- **payoffs**: chains of 3+ right after a setup move.',
  '- **traps**: tempting wrong chains (2+ trains off now, but not on a shortest path), summed over every step; **trapCost**: worst extra moves.',
  '- **moves**: the plan, one token per move: R = reverse setup, S = setup, number = trains sent off.',
  '',
  '| ' + cols.join(' | ') + ' |',
  '|' + cols.map(() => '---').join('|') + '|',
  ...rows.map((r) => '| ' + cols.map((k) => r[k]).join(' | ') + ' |'),
  '',
].join('\n');
fs.writeFileSync(path.join(root, 'prototypes/densha-domino/level-report.md'), md);
console.log(`wrote ${rows.length} levels`);
