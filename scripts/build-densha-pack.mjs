// Generates the Densha Domino level pack (levels 11 to 100) with the backwards generator
// and writes prototypes/densha-domino/src/game/pack.ts. Usage: node scripts/build-densha-pack.mjs
import { build } from 'esbuild';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import fs from 'node:fs';
import os from 'node:os';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(os.tmpdir(), `densha-pack-${process.pid}.mjs`);
await build({ entryPoints: [path.join(root, 'prototypes/densha-domino/src/game/generator.ts')], bundle: true, platform: 'node', format: 'esm', outfile: out, logLevel: 'error' });
const { generate } = await import(pathToFileURL(out).href);
const lerp = (a, b, t) => Math.round(a + (b - a) * t);
const items = [];
const seen = new Set();
for (let i = 0; i < 90; i++) {
  const stage = Math.floor(i / 30);
  const t = (i % 30) / 29;
  const [cols, rows, t0, t1] = [[6, 7, 8, 9], [7, 8, 10, 12], [8, 9, 12, 14]][stage];
  const trains = lerp(t0, t1, t);
  let r = null;
  for (let s = 0; s < 40 && !r; s++) {
    const minPar = Math.max(4, Math.round(trains * (0.55 - 0.02 * Math.min(s, 10))));
    const cand = generate({ cols, rows, trains, maxLen: 3, obstacles: 3 + stage * 2 + Math.floor(t * 2), climax: Math.min(3 + stage + Math.floor(t * 2), trains - 2), minPar, seed: 1000 + i * 50 + s });
    if (cand && !seen.has(cand.rows.join('/'))) r = cand;
  }
  if (!r) throw new Error(`no level for slot ${i + 11}`);
  seen.add(r.rows.join('/'));
  items.push({ rows: r.rows, axis: r.axis, par: r.par, exact: r.exact, climax: r.climaxLinks });
  console.log(`L${i + 11} ${cols}x${rows} trains ${trains} par ${r.par}${r.exact ? '' : '~'} climax ${r.climaxLinks}`);
}
const body = items.map((it, i) => `  { name: 'Line ${i + 11}', rows: ${JSON.stringify(it.rows)}, axis: ${JSON.stringify(it.axis)} },`).join('\n');
fs.writeFileSync(path.join(root, 'prototypes/densha-domino/src/game/pack.ts'), `import type { LevelSource } from './levels';\n\n// Generated by scripts/build-densha-pack.mjs (backwards generator). Do not edit by hand.\nexport const PACK: LevelSource[] = [\n${body}\n];\n`);
